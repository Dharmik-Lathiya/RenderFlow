#!/usr/bin/env bash
#
# Scheduled PostgreSQL backup to S3-compatible object storage (ARCH-09).
#
# Neon's own point-in-time recovery is the recommended option for the demo
# deployment; this script is the portable fallback for a self-hosted Postgres or
# for an operator who wants an independent copy outside the database provider.
# Run it from a cron service (Railway/Render scheduled job, Kubernetes CronJob,
# systemd timer) once a day. See docs/backup-restore.md.
#
# Required:
#   DATABASE_URL          source database (use a read-only role where possible)
#   BACKUP_S3_URL         e.g. s3://renderflow-backups/postgres
#
# Optional:
#   BACKUP_RETENTION_DAYS default 7
#   BACKUP_DRY_RUN=1      print the plan and exit without touching pg_dump/S3
#   AWS_* / AWS_ENDPOINT_URL  standard AWS CLI configuration (works with R2,
#                             MinIO and any S3-compatible endpoint)
#
# The dump contains password hashes and encrypted social tokens. It is written
# to a private temporary directory with mode 700 and deleted on exit; the
# uploaded object must live in a private bucket. Prefer a server-side-encrypted
# bucket; this script does not add a second layer of application encryption.

set -euo pipefail

if [[ "${BACKUP_DRY_RUN:-0}" == "1" ]]; then
  : "${BACKUP_S3_URL:?BACKUP_S3_URL is required, e.g. s3://bucket/postgres}"
  printf 'dry run: would dump DATABASE_URL and upload to %s (retention %s days)\n' \
    "${BACKUP_S3_URL%/}" "${BACKUP_RETENTION_DAYS:-7}"
  exit 0
fi

: "${DATABASE_URL:?DATABASE_URL is required (the source database)}"
: "${BACKUP_S3_URL:?BACKUP_S3_URL is required, e.g. s3://bucket/postgres}"

retention_days="${BACKUP_RETENTION_DAYS:-7}"
if ! [[ "$retention_days" =~ ^[0-9]+$ ]] || [[ "$retention_days" -lt 1 ]]; then
  echo "BACKUP_RETENTION_DAYS must be a positive integer, got '${retention_days}'" >&2
  exit 2
fi

for command in pg_dump pg_restore gzip sha256sum aws date; do
  if ! command -v "$command" >/dev/null 2>&1; then
    echo "required command not found: $command" >&2
    exit 2
  fi
done

base="${BACKUP_S3_URL%/}"
timestamp="$(date -u +%Y-%m-%dT%H-%M-%SZ)"
name="renderflow-${timestamp}.dump.gz"

workdir="$(mktemp -d)"
chmod 700 "$workdir"
trap 'rm -rf "$workdir"' EXIT
dump="$workdir/$name"

echo "== dumping the database"
# `--format=custom` is restorable table-by-table and with --clean. Piping through
# gzip keeps the upload small; pg_restore accepts a compressed custom-format dump
# directly.
pg_dump --format=custom --no-owner --no-privileges --file="$dump.tmp" "$DATABASE_URL"
gzip -9 "$dump.tmp"
mv "$dump.tmp.gz" "$dump"

# Prove the archive is readable BEFORE uploading it. A truncated dump that only
# fails at restore time is not a backup; it is a false sense of safety.
if ! pg_restore --list "$dump" >/dev/null; then
  echo "dump failed its integrity check; refusing to upload" >&2
  exit 1
fi

checksum="$(sha256sum "$dump" | awk '{print $1}')"
printf '%s  %s\n' "$checksum" "$name" > "$dump.sha256"
size="$(wc -c < "$dump" | tr -d ' ')"

echo "== uploading ${name} (${size} bytes, sha256 ${checksum})"
aws s3 cp --only-show-errors "$dump" "${base}/${name}"
aws s3 cp --only-show-errors "$dump.sha256" "${base}/${name}.sha256"

echo "== pruning objects older than ${retention_days} days"
cutoff="$(date -u -d "-${retention_days} days" +%Y-%m-%d)"
# Keys are generated by this script, so they contain no spaces. `aws s3 ls`
# prints "YYYY-MM-DD HH:MM:SS <size> <key>"; compare the date column and delete
# the two files that make up one backup.
while read -r day _ _ key; do
  [[ -z "${day:-}" || -z "${key:-}" ]] && continue
  [[ "$key" != renderflow-* ]] && continue
  if [[ "$day" < "$cutoff" ]]; then
    echo "   removing ${key}"
    aws s3 rm --only-show-errors "${base}/${key}"
  fi
done < <(aws s3 ls "${base}/")

echo "PASS: backup ${name} uploaded and retention applied"
