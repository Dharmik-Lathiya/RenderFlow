import type { Metadata } from 'next';
import { headers } from 'next/headers';
import type { ReactNode } from 'react';

import './globals.css';

import { Providers } from '../lib/providers';
import { SITE_DESCRIPTION, siteUrl } from '../lib/seo';
import { Shell } from '../components/shell';
import { appFontClassName } from './fonts';
import { PRE_HYDRATION_SCRIPT } from './boot-scripts';

/**
 * Root layout.
 *
 * `Providers` is a client component because react-query and the API context both
 * need the browser. Keeping it as the only client boundary here means the rest of
 * the tree can stay server components where there is nothing interactive to do.
 */
export const metadata: Metadata = {
  title: 'RenderFlow — AI marketing studio and social media scheduler',
  description: SITE_DESCRIPTION,
  applicationName: 'RenderFlow',
  /**
   * Resolves every relative canonical and Open Graph URL against the public
   * base URL, so sharing previews and canonicals are absolute even on a fresh
   * deployment that forgot the variable. See `lib/seo.ts`.
   */
  metadataBase: new URL(siteUrl()),
  openGraph: {
    type: 'website',
    siteName: 'RenderFlow',
  },
  /**
   * Site ownership verification. The token is public by design (Search Console
   * reads it from the published HTML), so it lives in code rather than config.
   */
  verification: {
    google: '6REvFHyIV-wFlDBJzKycrdcxadUeVbVTrnHygmOfScU',
  },
};

/**
 * `lang` and the skip link are not decoration.
 *
 * A screen reader picks its voice from `lang`, and the skip link is the only way
 * a keyboard user gets past the nav on every page - which is one of the two
 * things the Phase 8 DoD asks for by name.
 */
export default async function RootLayout({ children }: Readonly<{ children: ReactNode }>) {
  /**
   * The nonce generated by `proxy.ts` for THIS request.
   *
   * Reading a request header opts every page into dynamic rendering, which is
   * required for nonce-based CSP: a statically generated page is built before a
   * request exists, so its scripts carry no nonce and the browser blocks them.
   * That failure mode looks like "the form does nothing" rather than a CSP
   * error, so the rule is easy to miss.
   *
   * Next reads the same value from the `Content-Security-Policy` header and
   * applies it to its own bootstrap scripts; this attribute covers the one
   * inline script the app owns.
   */
  const nonce = (await headers()).get('x-nonce') ?? undefined;

  return (
    // The boot script adds `data-theme` before hydration; React must not treat
    // that deliberate attribute as a mismatch.
    <html lang="en" suppressHydrationWarning className={appFontClassName}>
      <body>
        {/*
          A native blocking script, deliberately not `next/script`: the
          `beforeInteractive` strategy queues the code for Next's runtime, which
          is late enough to paint the wrong theme for a frame. As the first node
          in the body it runs before any app markup is parsed. The composed
          script (theme boot + extension-attribute scrub) lives in
          `boot-scripts.ts`, where a spec executes it against a real DOM.
        */}
        <script nonce={nonce} dangerouslySetInnerHTML={{ __html: PRE_HYDRATION_SCRIPT }} />
        <a className="skip-link" href="#main">
          Skip to main content
        </a>
        <Providers>
          <Shell>{children}</Shell>
        </Providers>
      </body>
    </html>
  );
}
